import fs from 'node:fs';
import {Trial} from '../2026-10-13-origami-fold-trials/trial-lib.mjs';
import {publish} from './batch-001.mjs';
const t=new Trial('crab','Crab — Origami.me (batch 4)'),r=Math.SQRT1_2,a=r-.5;
const rec=(name,data)=>fs.writeFileSync(new URL(`batches/crab-${name}.json`,import.meta.url),JSON.stringify(data,null,2)+'\n');
let completed=0;
try{
 t.line([0,0],[1,1],[.8,.2],'1a: Precrease one diagonal, colored side up. Source: https://origami.me/crab/',{kind:'precrease'});
 t.line([0,1],[1,0],[.2,.2],'1b: Precrease the second diagonal.',{kind:'precrease'});completed=1;
 t.turn('2a: Turn over.');
 t.line([-.5,0],[-.5,1],[-.8,.5],'2b: Precrease vertically.',{kind:'precrease'});
 t.line([-1,.5],[0,.5],[-.5,.2],'2c: Precrease horizontally.',{kind:'precrease'});completed=2;
 t.add({kind:'rotate',rotate:{amount:'eighth',direction:'cw'}},'3a: Rotate 45° clockwise.');
 t.pp([0,2*r],[0,0],'3b: Bring the upper point down.');
 t.pp([-r,r],[r,r],'3c: Bring the left half over to the right.');
 t.add({kind:'squash',flap:t.at([.35,.59]),direction:'valley'},'3d: Squash the first pocket.');
 t.turn('3e: Turn over to expose the second pocket.');
 t.add({kind:'squash',flap:t.at([-.35,.59]),direction:'valley'},'3f: Squash the second pocket to complete the square base.');completed=3;
 t.line([0,r],[a,a],[.3,.35],'4: Precrease the front right flap to the centerline.',{kind:'precrease',scope:2});completed=4;
 rec('before-first-squash',t.scene());
 const op={kind:'squash',flap:t.at([.3,.36]),direction:'valley'};rec('first-squash-attempt',{op,analysis:t.e.compound_analysis(t.state,op)});
 t.add(op,'5: Open the right flap and squash it onto the centerline.');completed=5;
 rec('after-first-squash',t.scene());
 t.turn('6a: Turn over.');
 t.line([0,r],[a,a],[.3,.35],'6b: Precrease the matching right flap.',{kind:'precrease',scope:2});
 t.add({kind:'squash',flap:t.at([.3,.36]),direction:'valley'},'6c: Squash the matching pocket.');
 t.turn('6d: Return to the front.');completed=6;
 t.line([0,.25],[0,r],[.08,.4],'7a: Flip the front right page to the left.',{scope:1});
 t.turn('7b: Turn over.');
 t.line([0,.25],[0,r],[.08,.4],'7c: Flip the back right page to the left.',{scope:1});
 t.turn('7d: Return to the front.');completed=7;
 t.line([0,r],[a,a],[.3,.35],'8: Precrease the remaining front right flap.',{kind:'precrease',scope:2});completed=8;
 t.add({kind:'squash',flap:t.at([.3,.36]),direction:'valley'},'9: Squash the remaining front pocket.');completed=9;
 t.turn('10a: Turn over.');
 t.line([0,r],[a,a],[.3,.35],'10b: Precrease the remaining back right flap.',{kind:'precrease',scope:2});
 t.add({kind:'squash',flap:t.at([.3,.36]),direction:'valley'},'10c: Squash the last pocket.');
 t.turn('10d: Return to the front.');completed=10;
 rec('before-petal',t.scene());
 const c=(1-r)/2;
 const uncreasedPetal={kind:'petal',ends:[t.at([-c,r/2]),t.at([c,r/2])],petal:t.at([.01,.23]),direction:'valley'};
 const uncreasedResult=t.e.apply(t.state,uncreasedPetal);
 rec('uncreased-petal-control',{op:uncreasedPetal,result:uncreasedResult,...(uncreasedResult.status==='ok'?{scene:t.e.scene(uncreasedResult.state)}:{})});
 t.line([0,0],[-c,r/2],[-.15,.23],'11a: Precrease the front left lower edge to the center.',{kind:'precrease',scope:1});
 t.line([0,0],[c,r/2],[.15,.23],'11b: Precrease the front right lower edge to the center.',{kind:'precrease',scope:1});completed=11;
 const petal={kind:'petal',ends:[t.at([-c,r/2]),t.at([c,r/2])],petal:t.at([.01,.23]),direction:'valley'};rec('petal-attempt',{op:petal,analysis:t.e.compound_analysis(t.state,petal)});
 t.add(petal,'12: Lift the front flap into a petal along the reference creases.');completed=12;
 rec('after-petal',t.scene());
}catch(error){rec('failure',{completed,message:error.message,log:t.log});}
publish(t,'https://origami.me/crab/',{sourceSteps:32,sourceStepsCompleted:completed,sourceDiagramsReviewed:34,audit:'pending visual review'});
