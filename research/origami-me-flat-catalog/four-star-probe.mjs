import fs from 'node:fs';
import {Trial} from '../2026-10-13-origami-fold-trials/trial-lib.mjs';
import {publish} from './batch-001.mjs';
const t=new Trial('4-pointed-star','Four-Pointed Star — Origami.me (batch 4)',{shape:{kind:'square'},startSide:'back'});
const r=Math.SQRT1_2,a=1-r;
const rec=(name,data)=>fs.writeFileSync(new URL(`batches/4-pointed-star-${name}.json`,import.meta.url),JSON.stringify(data,null,2)+'\n');
let completed=0;
try {
 t.add({kind:'rotate',rotate:{amount:'eighth',direction:'cw'}},'Set-up: white side up, diamond orientation. Source: https://origami.me/4-pointed-star/');
 t.line([0,0],[0,2*r],[.3,.7],'1a: Precrease the vertical diagonal.',{kind:'precrease'});
 t.line([-r,r],[r,r],[0,.2],'1b: Precrease the horizontal diagonal.',{kind:'precrease'});completed=1;
 const partial=(p,q,m,note)=>t.add({kind:'precrease',direction:'valley',line:{via:'free',through:[t.at(p),t.at(q)]},moving:t.at(m),seed:{scope:'all'},extent:{kind:'segment',from:{kind:'point',at:t.at(p)},to:{kind:'point',at:t.at(q)}}},note);
 partial([0,0],[-a,r],[-.3,.5],'2: Align the lower-left edge with the center; crease only up to the horizontal center.');completed=2;
 partial([0,2*r],[-a,r],[-.3,.9],'3: Align the upper-left edge with the center; stop at the horizontal center.');completed=3;
 partial([0,0],[a,r],[.3,.5],'4a: Repeat the lower partial crease on the right.');
 partial([0,2*r],[a,r],[.3,.9],'4b: Repeat the upper partial crease on the right.');completed=4;
 t.add({kind:'rotate',rotate:{amount:'quarter',direction:'cw'}},'5: Rotate 90 degrees clockwise.');completed=5;
 partial([r,-r],[r-a,0],[r-.3,-.2],'6a: Repeat the lower-left partial crease.');
 partial([r,r],[r-a,0],[r-.3,.2],'6b: Repeat the upper-left partial crease.');
 partial([r,-r],[r+a,0],[r+.3,-.2],'6c: Repeat the lower-right partial crease.');
 partial([r,r],[r+a,0],[r+.3,.2],'6d: Repeat the upper-right partial crease.');
 t.add({kind:'rotate',rotate:{amount:'eighth',direction:'cw'}},'6e: Rotate another 45 degrees clockwise into square orientation.');completed=6;
 t.line([r/2,-1],[r/2,0],[.1,-.5],'7: Align the left edge with the two right-hand inner intersections, then unfold.',{kind:'precrease'});completed=7;
 t.line([0,-1+r/2],[1,-1+r/2],[.5,-.9],'8: Align the bottom edge with the upper inner intersections, then unfold.',{kind:'precrease'});completed=8;
 t.add({kind:'turn',axis:'horizontal'},'9: Turn over from top to bottom.');completed=9;
 t.line([0,.5],[1,.5],[.2,.8],'10: Fold the top half down.');completed=10;
 t.line([0,r/2],[1,r/2],[.2,.1],'11: Fold the front layer upward along its existing crease.',{scope:1});completed=11;
 t.line([.5,0],[.5,r],[.1,.4],'12: Fold the left half rightward.');completed=12;
 t.line([1-r/2,0],[1-r/2,r],[.9,.2],'13: Fold the front layer leftward along its existing crease.',{scope:1});completed=13;
 t.turn('14: Turn over from left to right.');completed=14;
 rec('before-swivel',t.scene());
 const op={kind:'swivel',via:'edge',fold:t.at([-.5,.6]),edge:t.at([-.8,r]),target:{via:'free',through:[t.at([-1,r]),t.at([-.6,r-.4])]},direction:'valley',swivel:'open'};
 rec('swivel-attempt',{op,analysis:t.e.compound_analysis(t.state,op)});
 t.add(op,'15: Swivel the upper-left top edge down onto its diagonal, opening the fold at the right of that panel.');completed=15;
 rec('after-swivel',t.scene());
}catch(error){rec('failure',{completed,message:error.message,log:t.log});}
publish(t,'https://origami.me/4-pointed-star/',{sourceSteps:20,sourceStepsCompleted:completed,sourceDiagramsReviewed:21,audit:'pending visual review'});
